let language = 'zh-Hant';
const bindings = new Map();
const staticText = [];
const staticAttributes = [];

export function getLanguage() { return language; }
export function tr(source, ...values) {
  const key = Array.isArray(source) ? source.reduce((text, part, index) => text + (index ? `{${index - 1}}` : '') + part, '') : String(source ?? '');
  const template = language === 'en' ? english[key] ?? backendDetail(key, language) : key;
  return template.replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ''));
}

// Keep the source message and its values so a language change can update an
// existing alert or playback status without restarting any capture resources.
export function uiText(element, render) {
  bindings.set(element, render);
  element.textContent = render();
}

export function initializeTranslations() {
  const walker = document.createTreeWalker(document, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest('script, style, code, [translate="no"]')) continue;
    const source = node.textContent.trim();
    if (Object.hasOwn(english, source)) staticText.push({ node, source, leading: node.textContent.match(/^\s*/)[0], trailing: node.textContent.match(/\s*$/)[0] });
  }
  document.querySelectorAll('[aria-label], [title], [alt]').forEach(element => {
    for (const attribute of ['aria-label', 'title', 'alt']) {
      const source = element.getAttribute(attribute);
      if (source && Object.hasOwn(english, source)) staticAttributes.push({ element, attribute, source });
    }
  });
}

export function setLanguage(next) {
  language = next === 'en' ? 'en' : 'zh-Hant';
  document.documentElement.lang = language;
  for (const { node, source, leading, trailing } of staticText) if (node.isConnected) node.textContent = leading + tr(source) + trailing;
  for (const { element, attribute, source } of staticAttributes) element.setAttribute(attribute, tr(source));
  for (const [element, render] of bindings) if (element.isConnected) element.textContent = render();
  document.getElementById('interface-language').value = language;
}
