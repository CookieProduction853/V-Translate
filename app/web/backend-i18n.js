function backendName(value) {
  return value.replace('Apple Metal 顯卡', 'Apple Metal GPU').replace('Vulkan 顯卡', 'Vulkan GPU');
}

function assetName(value) {
  return value.replace('CPU 語音引擎', 'the CPU transcription engine')
    .replace('Vulkan 顯卡翻譯引擎', 'the Vulkan GPU translation engine')
    .replace('CPU 翻譯引擎', 'the CPU translation engine');
}

const fallback = 'The local AI service reported an unexpected issue. Check its logs for details.';
const fragments = [...messages.entries()].sort((a, b) => b[0].length - a[0].length);

function englishDetail(value) {
  const detail = String(value ?? '');
  if (!detail || !/\p{Script=Han}/u.test(detail)) return detail;
  if (messages.has(detail)) return messages.get(detail);
  for (const [pattern, render, preservesFilename] of patterns) {
    const match = detail.match(pattern);
    if (match) {
      const translated = render(...match);
      // Model filenames are user data and may legitimately contain Chinese.
      return !preservesFilename && /\p{Script=Han}/u.test(translated) ? fallback : translated;
    }
  }
  // anyhow error chains combine the known context with an engine or OS error.
  // Replace long contexts first so a shorter diagnostic cannot consume them.
  let translated = detail;
  for (const [source, target] of fragments) translated = translated.split(source).join(target);
  if (!/\p{Script=Han}/u.test(translated)) return translated;
  // Unknown future diagnostics get an English fallback rather than exposing an
  // untranslated service message in an otherwise English interface.
  return fallback;
}

export function backendDetail(detail, language = 'zh-Hant') {
  return language === 'en' ? englishDetail(detail) : String(detail ?? '');
}
